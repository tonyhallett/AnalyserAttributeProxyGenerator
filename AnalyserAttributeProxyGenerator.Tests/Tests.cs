            internal AttributeSettings Build() => new(_returnType, _returnTypeIsNullableReferenceType, _methodName, _generateNullableReferenceTypes);
        }

        private class ProxySettingsBuilder
        {
            private bool _isStatic;
            private string _namespace = "SourceNs";
            private string[] _proxiedAttributeConstructorParams = ["string name"];

            public ProxySettingsBuilder WithIsStatic()
            {
                _isStatic = true;
                return this;
            }

            public ProxySettingsBuilder WithGlobalNamespace()
            {
                _namespace = string.Empty;
                return this;
            }

            public ProxySettingsBuilder WithNamespace(string proxyNamespace)
