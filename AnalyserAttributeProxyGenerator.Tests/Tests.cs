                return this;
            }

            public ProxySettingsBuilder WithProxiedAttributeConstructorParams(params string[] proxiedAttributeConstructorParams)
            {
                if (_proxiedAttributeConstructorParams.Length == 0)
                {
                    throw new InvalidOperationException("Proxied attribute constructor parameters must be specified");
                }

                _proxiedAttributeConstructorParams = proxiedAttributeConstructorParams;
                return this;
            }

            internal ProxySettings Build() => new(_isStatic, _namespace, _proxiedAttributeConstructorParams);
        }

        private class SourceBuilder
        {
            public const string AnEnum = "AnEnum";
            private readonly ProxySettingsBuilder _proxySettings = new();
            private readonly AttributeSettingsBuilder _attributeSettings = new();

            public SourceBuilder WithProxySettings(Action<ProxySettingsBuilder> configure)
            {
                configure(_proxySettings);
                return this;
            }

            public SourceBuilder WithAttributeSettings(Action<AttributeSettingsBuilder> configure)
            {
                configure(_attributeSettings);
                return this;
            }

            public string Build() => GetSource(_proxySettings.Build(), _attributeSettings.Build());

            private static string GetSource(ProxySettings proxySettings, AttributeSettings attributeSettings)
            {
                string namespaceStart = string.Empty;
                string namespaceEnd = string.Empty;
                if (!string.IsNullOrEmpty(proxySettings.Namespace))
                {
                    namespaceStart =
    $$"""
namespace {{proxySettings.Namespace}}
{
""";
                    namespaceEnd = "}";
                }

                const string prAtt = "typeof(AttributeNs.ProxiedAttribute)";
                string rt = $" typeof({attributeSettings.ReturnType})";
                string rtnrt = attributeSettings.ReturnTypeIsNullableReferenceType ? "true" : "false";
                string attribute = $"[{ProxyGenerator.FullyQualifiedAttributeName}({prAtt}, {rt}, {rtnrt}";
                if (string.IsNullOrEmpty(attributeSettings.MethodName))
                {
                    attribute += ")]";
                }
                else
                {
                    attribute += $", \"{attributeSettings.MethodName}\", {(attributeSettings.GenerateNullableReferenceTypes ? "true" : "false")})]";
                }

                StringBuilder ctorsBuilder = new();
                foreach (string ctorParams in proxySettings.ProxiedAttributeConstructorParams)
                {
                    ctorsBuilder.AppendLine(CultureInfo.InvariantCulture, $"        public ProxiedAttribute({ctorParams}) {{ }}");
                }

                string staticKeyword = proxySettings.IsStatic ? "static " : string.Empty;

                return
    $$"""
{{namespaceStart}}
    {{attribute}}
    {{staticKeyword}}partial class Proxy
    { }
{{namespaceEnd}}
namespace AttributeNs
{
    public class ProxiedAttribute : System.Attribute
    {
{{ctorsBuilder}}
    }
}
public enum {{AnEnum}} {}
""";
            }
        }
