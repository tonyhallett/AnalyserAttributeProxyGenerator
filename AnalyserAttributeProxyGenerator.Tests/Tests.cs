        {
            private string _returnType = "string";
            private bool _returnTypeIsNullableReferenceType;
            private string _methodName = string.Empty;
            private bool _generateNullableReferenceTypes;

            public AttributeSettingsBuilder WithReturnType(string returnType)
            {
                _returnType = returnType;
                return this;
            }

            public AttributeSettingsBuilder WithReturnTypeIsNullableReferenceType()
            {
                _returnTypeIsNullableReferenceType = true;
                return this;
            }

            public AttributeSettingsBuilder WithMethodName(string methodName)
            {
                _methodName = methodName;
                return this;
            }

            public AttributeSettingsBuilder WithGenerateNullableReferenceTypes()
