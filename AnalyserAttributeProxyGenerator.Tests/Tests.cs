        private record ProxySettings(bool IsStatic, string Namespace, string[] ProxiedAttributeConstructorParams);

        private record AttributeSettings(string ReturnType, bool ReturnTypeIsNullableReferenceType, string MethodName, bool GenerateNullableReferenceTypes);

